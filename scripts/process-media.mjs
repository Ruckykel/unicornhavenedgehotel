// Converts client-supplied media in /pictures and /videos into web-ready
// assets under /public/media (see blueprint §11) and writes a manifest with
// dimensions + blur placeholders for next/image.
//
// Run: npm run media
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync, existsSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import sharp from "sharp";
import ffmpegPath from "ffmpeg-static";
import potrace from "potrace";

const ROOT = process.cwd();
const OUT = join(ROOT, "public", "media");
const TMP = join(ROOT, ".media-tmp");

// source file -> published path (without extension)
const IMAGES = {
  "frontview1.png": "spaces/exterior-facade",
  "frontview2.png": "spaces/entrance-porch",
  "frontview3.png": "spaces/glass-entrance",
  "compoundspace.png": "spaces/courtyard-parking",
  "streetlandmarksign.png": "spaces/street-sign",
  "unicornhavenaerialview.png": "spaces/aerial-front",
  "unicornhavenaerialview2.png": "spaces/aerial-wide",
  "reception.png": "spaces/reception",
  "loungerestaurantview.png": "dining/lounge",
  "loungerestaurantview2.png": "dining/lounge-seating",
  "drinksshelf.png": "dining/bar-shelf",
  "room1.png": "rooms/classic-room/01",
  "room2.png": "rooms/classic-room/02",
  "room3.png": "rooms/deluxe-room/01",
  "room4.png": "rooms/executive-suite/01",
};

// stills pulled from the supplied videos: [video, seconds, published path]
const STILLS = [
  ["restaurant.mp4", 2.6, "hero/hero-poster"],
  ["restaurant.mp4", 24.6, "dining/plantain-rice"],
  ["restaurant.mp4", 28.2, "dining/vegetable-salad"],
  ["restaurant.mp4", 20.5, "dining/lounge-corner"],
  ["hotel.mp4", 0.6, "spaces/lobby-seating"],
  ["hotel.mp4", 10.5, "spaces/corridor"],
  ["hotel.mp4", 19.5, "rooms/walkthrough/01"],
  ["hotel.mp4", 22.6, "rooms/walkthrough/02"],
  ["hotel.mp4", 17.5, "rooms/walkthrough/03"],
];

const ff = (args) => execFileSync(ffmpegPath, ["-v", "error", "-y", ...args], { stdio: "inherit" });
const ensureDir = (file) => mkdirSync(dirname(file), { recursive: true });

async function processImage(input, outPath, manifest) {
  const file = join(OUT, `${outPath}.jpg`);
  ensureDir(file);
  const img = sharp(input).rotate();
  const { width, height } = await img
    .clone()
    .resize({ width: 2400, height: 2400, fit: "inside", withoutEnlargement: true })
    .jpeg({ quality: 84, mozjpeg: true })
    .toFile(file);
  const blur = await img.clone().resize(16).jpeg({ quality: 50 }).toBuffer();
  manifest[`/media/${outPath}.jpg`] = {
    width,
    height,
    blurDataURL: `data:image/jpeg;base64,${blur.toString("base64")}`,
  };
  console.log("image", outPath, `${width}x${height}`);
}

async function traceLogo() {
  // Trace only the rearing unicorn (centre of the badge); the ring and the
  // circular lettering are redrawn as real SVG so they stay crisp at 40px.
  const src = join(ROOT, "pictures", "unicornhavenedgehotellogo.png");
  const meta = await sharp(src).metadata();
  const crop = { left: 89, top: 91, width: 284, height: 284 };
  const SCALE = 4;
  const size = crop.width * SCALE;
  const { data } = await sharp(src)
    .flatten({ background: "#ffffff" })
    .extract(crop)
    .resize(size, size)
    .grayscale()
    .raw()
    .toBuffer({ resolveWithObject: true });
  // Whiten everything outside the inner ring (the outer lettering) and
  // threshold high enough that the faint watermark over the body stays black.
  const c = size / 2;
  const r = c - 4 * SCALE;
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      const i = y * size + x;
      const outside = (x - c) ** 2 + (y - c) ** 2 > r * r;
      data[i] = outside || data[i] > 185 ? 255 : 0;
    }
  }
  const buf = await sharp(data, { raw: { width: size, height: size, channels: 1 } }).png().toBuffer();
  const svg = await new Promise((res, rej) =>
    potrace.trace(buf, { threshold: 128, turdSize: 40, optTolerance: 0.4 }, (e, s) => (e ? rej(e) : res(s)))
  );
  const d = svg.match(/ d="([^"]+)"/)[1];
  return { d, viewBox: `0 0 ${crop.width * 4} ${crop.height * 4}`, source: meta };
}

function writeLogo(logo) {
  const file = join(ROOT, "src", "lib", "unicorn-path.ts");
  ensureDir(file);
  writeFileSync(
    file,
    `// Generated by scripts/process-media.mjs from the client's badge logo.
export const UNICORN_VIEWBOX = "${logo.viewBox}";
export const UNICORN_PATH =
  "${logo.d}";
`
  );
  console.log("logo traced, path length", logo.d.length);
}

async function main() {
  // LOGO_ONLY=1 npm run media -> re-trace the logo without re-encoding media
  if (process.env.LOGO_ONLY) return writeLogo(await traceLogo());
  mkdirSync(TMP, { recursive: true });
  const manifest = {};

  for (const [src, out] of Object.entries(IMAGES)) {
    await processImage(join(ROOT, "pictures", src), out, manifest);
  }

  for (const [video, t, out] of STILLS) {
    const tmp = join(TMP, `${out.replace(/\//g, "_")}.png`);
    ff(["-ss", String(t), "-i", join(ROOT, "videos", video), "-frames:v", "1", tmp]);
    await processImage(tmp, out, manifest);
  }

  // Videos. Sources are vertical 1080x1920 @60fps, ~18Mbps, silent audio.
  const vids = [
    // hero loop: the arrival (courtyard -> timber porch), muted
    { src: "restaurant.mp4", out: "hero/hero-loop.mp4", ss: 0, t: 8.4, w: 720, crf: 28 },
    { src: "restaurant.mp4", out: "hero/hero-loop-hd.mp4", ss: 0, t: 8.4, w: 1080, crf: 26 },
    // brand film: interior walkthrough
    { src: "hotel.mp4", out: "brand/brand-film.mp4", ss: 0, t: 25, w: 720, crf: 27 },
    // dining film: arrival, lounge and plates
    { src: "restaurant.mp4", out: "dining/dining-film.mp4", ss: 0, t: 29, w: 720, crf: 27 },
  ];
  for (const v of vids) {
    const file = join(OUT, v.out);
    ensureDir(file);
    ff([
      "-ss", String(v.ss), "-t", String(v.t), "-i", join(ROOT, "videos", v.src),
      "-an", "-vf", `scale=${v.w}:-2,fps=30`,
      "-c:v", "libx264", "-preset", "slow", "-crf", String(v.crf), "-profile:v", "high",
      "-pix_fmt", "yuv420p", "-movflags", "+faststart", file,
    ]);
    console.log("video", v.out);
  }

  const libFile = join(ROOT, "src", "lib", "media-manifest.json");
  ensureDir(libFile);
  writeFileSync(libFile, JSON.stringify(manifest, null, 2));
  writeLogo(await traceLogo());

  if (existsSync(TMP)) rmSync(TMP, { recursive: true, force: true });
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
